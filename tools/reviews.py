#!/usr/bin/env python3
"""Mirror the reviews written on other sites into the blog.

Every review on the accounts in ``data/reviews.toml`` becomes one post under
``content/blog/reviews/<site>/``, dated when the review was posted, so the
blog feed interleaves them with everything else in the order they were
written. The posts are generated and owned by this script: each run rewrites
every one of them from the source and deletes the ones whose review has gone.
The sources are the copy that matters -- fix an old review where it was
written, then pull it back down.

Three sources, three ways in:

``steam``
    The profile's ``/recommended/`` pages for the list of games, then each
    review's own page, which is the only place Steam prints the minute a
    review was posted and the hours played at the time. Requested with a UTC
    timezone cookie so the times it prints are UTC.
``goodreads``
    The shelf's RSS feed, which carries the review HTML, the rating and the
    dates. Goodreads hides review pages behind a sign-in, and the feed drops
    spoiler-tagged passages, leaving the words ``[spoilers removed]`` where
    one was; each becomes a link to the review where the passage still is.
``vndb``
    The user's review list and each review's page, then one call to the VNDB
    API for the novels' titles, covers and release dates.

Nothing here is automatic on purpose. ``pull`` rewrites the posts and leaves
the result in the working tree to be read as a diff and committed by hand;
``check`` does the same work without writing and reports how far behind the
committed posts are, which is all CI does with it.

Usage::

    python tools/reviews.py pull                  # every site
    python tools/reviews.py pull steam vndb       # just these
    python tools/reviews.py check                 # report drift, write nothing
    python tools/reviews.py check --github        # ...as CI annotations
"""

