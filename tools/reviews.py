def slugify(text: str) -> str:
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.lower().replace("'", "")).strip("-")
    return slug[:60].rstrip("-")


def _yaml(value: object) -> str:
    """Write a scalar or list as YAML.

    JSON is YAML, so everything but dates goes through ``json.dumps`` and
    comes out quoted and escaped correctly without a YAML library.

    :param value: What to write.
    :return: Its YAML spelling.
    """
    if isinstance(value, datetime):
        return value.isoformat()
    return json.dumps(value, ensure_ascii=False)


def render(review: Review, slug: str, zone: ZoneInfo, account: dict[str, Any]) -> str:
    """Write one review out as a blog post.

    :param review: The review.
    :param slug: Its URL slug, already made unique within the site.
    :param zone: The zone timestamps are written in.
    :param account: The site's table from the config.
    :return: The whole file.
    """

    def local(stamp: datetime) -> datetime:
        # VNDB gives a bare date; it is a date where the reviewer was.
        if stamp.tzinfo is None:
            return stamp.replace(tzinfo=zone)
        return stamp.astimezone(zone)

    meta: list[tuple[str, object]] = [
        ("site", review.site),
        ("url", review.url),
    ]
    if review.updated and review.updated != review.date:
        meta.append(("updated", local(review.updated)))
    meta.append(("item_url", review.item_url))
    if review.image:
        meta.append(("image", review.image))
    if review.image_width and review.image_height:
        meta += [
            ("image_width", review.image_width),
            ("image_height", review.image_height),
        ]
    meta += list(review.fields.items())
    lines = [
        "---",
        f"{GENERATED_MARK} from {account['name']}. Edit the review at",
        f"# {review.url} and pull it again; changes made here are overwritten.",
        f"title: {_yaml(review.title)}",
        f"date: {local(review.date).isoformat()}",
        f"slug: {_yaml(slug)}",
        'type: "review"',
        f"theme: {_yaml(review.site)}",
        'tags: ["review"]',
        "review:",
        # An absent field is left out rather than written empty, so a review
        # that gains one later shows up in the diff as a line added.
        *(
            f"  {key}: {_yaml(value)}"
            for key, value in meta
            if value is not None and value not in ("", [])
        ),
        "---",
        "",
        '<div class="review-text">',
        review.body,
        "</div>",
        "",
    ]
    return "\n".join(lines)


def plan(
    site: str, reviews: Iterable[Review], zone: ZoneInfo, account: dict[str, Any]
) -> dict[Path, str]:
    """Work out every file a site's reviews should produce.

    The file is named for the review's id at the source, which never changes
    and is what the Atom feed keys an entry on (layouts/blog/list.rss.xml), so
    a retitled game is an edited entry rather than a new one. The URL is
    named for the title, through ``slug``.

    :param site: Which site.
    :param reviews: Its reviews.
    :param zone: The zone timestamps are written in.
    :param account: The site's table from the config.
    :return: Path to contents.
    """
    files: dict[Path, str] = {}
    taken: set[str] = set()
    for review in sorted(reviews, key=lambda r: (r.date.replace(tzinfo=None), r.key)):
        slug = slugify(review.title) or review.key
        if slug in taken:
            slug = f"{slug}-{slugify(review.key)}"
        taken.add(slug)
        path = CONTENT / site / f"{site}-{slugify(review.key)}.md"
        files[path] = render(review, slug, zone, account)
    return files


def owned(site: str) -> set[Path]:
    """Return the files already on disk that this script generated for a site.

    :param site: Which site.
    :return: Their paths.
    """
    directory = CONTENT / site
    if not directory.is_dir():
        return set()
    return {
        path
        for path in directory.glob("*.md")
        if GENERATED_MARK
        in "".join(path.read_text(encoding="utf-8").split("\n", 2)[1:2])
    }


@dataclass
class Drift:
    added: list[Path] = field(default_factory=list)
    changed: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.added) + len(self.changed) + len(self.removed)


def compare(site: str, files: dict[Path, str]) -> Drift:
    drift = Drift()
    for path, text in files.items():
        if not path.exists():
            drift.added.append(path)
        elif path.read_text(encoding="utf-8") != text:
            drift.changed.append(path)
    drift.removed = sorted(owned(site) - files.keys())
    return drift


# -------------------------------------------------------------------- CLI


def _load_config() -> tuple[dict[str, Any], ZoneInfo]:
    with CONFIG.open("rb") as handle:
        config = tomllib.load(handle)
    return config, ZoneInfo(config["timezone"])


def _gather(sites: list[str]) -> dict[str, tuple[dict[Path, str], Drift]]:
    config, zone = _load_config()
    results = {}
    for site in sites:
        _logger.info("%s: fetching", site)
        reviews = PULLERS[site](config[site])
        files = plan(site, reviews, zone, config[site])
        results[site] = (files, compare(site, files))
        _logger.info("%s: %d review(s)", site, len(files))
    return results


def _rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def cmd_pull(sites: list[str]) -> int:
    """Rewrite the posts from the sources.

    A site is written only once all of it has been read, so a request that
    fails halfway leaves that site's posts as they were rather than half
    deleted.

    :param sites: Which sites to pull.
    :return: Process exit code.
    """
    for site, (files, drift) in _gather(sites).items():
        for path in drift.added + drift.changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(files[path], encoding="utf-8", newline="\n")
        for path in drift.removed:
            path.unlink()
        _logger.info(
            "%s: %d added, %d changed, %d removed",
            site,
            len(drift.added),
            len(drift.changed),
            len(drift.removed),
        )
        for label, paths in (
            ("+", drift.added),
            ("~", drift.changed),
            ("-", drift.removed),
        ):
            for path in paths:
                _logger.info("  %s %s", label, _rel(path))
    return 0


def cmd_check(sites: list[str], *, github: bool, strict: bool) -> int:
    """Report how far the committed posts are behind the sources.

    :param sites: Which sites to check.
    :param github: Also write workflow annotations and a job summary.
    :param strict: Exit 1 when anything is behind.
    :return: Process exit code.
    """
    results = _gather(sites)
    rows = []
    behind = 0
    for site, (files, drift) in results.items():
        behind += len(drift)
        rows.append((site, len(files), drift))
        _logger.info(
            "%s: %d new, %d changed, %d gone",
            site,
            len(drift.added),
            len(drift.changed),
            len(drift.removed),
        )
        for label, paths in (
            ("new", drift.added),
            ("changed", drift.changed),
            ("gone", drift.removed),
        ):
            for path in paths:
                _logger.info("  %s %s", label, _rel(path))
    verdict = (
        f"{behind} review post(s) behind;"
        " run `python tools/reviews.py pull` and commit the result"
        if behind
        else "every review post is up to date"
    )
    _logger.info("%s", verdict)
    if github:
        if behind:
            sys.stdout.write(f"::warning title=Reviews behind::{verdict}\n")
        summary = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary:
            table = [
                "## Reviews",
                "",
                "| Site | At source | New | Changed | Gone |",
                "| --- | ---: | ---: | ---: | ---: |",
                *(
                    f"| {site} | {total} | {len(d.added)} | {len(d.changed)}"
                    f" | {len(d.removed)} |"
                    for site, total, d in rows
                ),
                "",
                verdict,
                "",
            ]
            with Path(summary).open("a", encoding="utf-8") as handle:
                handle.write("\n".join(table))
    return 1 if strict and behind else 0


def main() -> int:
    """Execute the CLI entry point.

    :return: Exit code (0 for success, non-zero for error).
    """
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="count",
        default=0,
        help="Increase verbosity (can be repeated)",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)
    pull = subparsers.add_parser(
        "pull", help="Rewrite content/blog/reviews/ from the sources"
    )
    check = subparsers.add_parser(
        "check", help="Report what a pull would change; write nothing"
    )
    for sub in (pull, check):
        sub.add_argument(
            "sites",
            nargs="*",
            metavar="site",
            help=f"Sites to read (default: all of {', '.join(SITES)})",
        )
    check.add_argument(
        "--github",
        action="store_true",
        help="Emit a workflow annotation and a job summary",
    )
    check.add_argument(
        "--strict",
        action="store_true",
        help="Exit 1 when any post is behind its source",
    )
    args = parser.parse_args()
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(message)s",
    )
    unknown = sorted(set(args.sites) - set(SITES))
    if unknown:
        parser.error(
            f"unknown site(s): {', '.join(unknown)} (choose from {', '.join(SITES)})"
        )
    sites = list(dict.fromkeys(args.sites)) or list(SITES)
    try:
        if args.command == "pull":
            return cmd_pull(sites)
        return cmd_check(sites, github=args.github, strict=args.strict)
    except (urllib.error.URLError, ValueError, ET.ParseError) as error:
        _logger.error("%s", error)
        return 2


if __name__ == "__main__":
    sys.exit(main())
